// Mirrors every top-level `@media (hover: hover)` rule onto `:active`, so a
// touch device shows the same highlight while a finger is held down.
//
// Run after changing a hover rule:  node scripts/gen-touch-press.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCES = ['src/styles/layout.css', 'src/styles/cards.css']
const OUT = 'src/styles/touch-press.css'

// The ranges covered by desktop-only media queries — hover rules inside those
// describe the desktop layout and must not leak onto phones.
function desktopRanges(css) {
  const out = []
  const re = /@media[^{]*min-width[^{]*\{/g
  let m
  while ((m = re.exec(css))) {
    let i = m.index + m[0].length
    let depth = 1
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++
      else if (css[i] === '}') depth--
      i++
    }
    out.push([m.index, i])
    re.lastIndex = i
  }
  return out
}

// Pull out @media (hover: hover) blocks (balanced braces), skipping any that sit
// inside a desktop-only media query.
function hoverBlocks(css) {
  const out = []
  const skip = desktopRanges(css)
  const re = /@media\s*\(hover:\s*hover\)\s*\{/g
  let m
  while ((m = re.exec(css))) {
    if (skip.some(([a, b]) => m.index > a && m.index < b)) continue
    let i = m.index + m[0].length
    let depth = 1
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++
      else if (css[i] === '}') depth--
      i++
    }
    out.push(css.slice(m.index + m[0].length, i - 1))
    re.lastIndex = i
  }
  return out
}

// Inside a hover block, a rule whose selector has no :hover isn't a hover state
// at all — it's desktop-only setup (e.g. hiding an icon until hover). Mirroring
// it onto touch would apply desktop behaviour to phones, so drop it.
function hoverRulesOnly(block) {
  const out = []
  let i = 0
  while (i < block.length) {
    const open = block.indexOf('{', i)
    if (open === -1) break
    let j = open + 1
    let depth = 1
    while (j < block.length && depth > 0) {
      if (block[j] === '{') depth++
      else if (block[j] === '}') depth--
      j++
    }
    const rule = block.slice(i, j)
    const selector = block.slice(i, open)
    if (selector.includes(':hover')) out.push(rule.trim())
    i = j
  }
  return out.join('\n')
}

const body = SOURCES.flatMap(f => hoverBlocks(readFileSync(f, 'utf8')))
  .map(hoverRulesOnly)
  .join('\n')
  .replace(/:hover/g, '.is-pressed')

writeFileSync(OUT, `/* GENERATED by scripts/gen-touch-press.mjs — do not edit by hand.
   Every desktop hover rule, mirrored onto the .is-pressed class that
   src/pressState.js maintains, so pressing an element on a touch device shows
   the same highlight until the finger lifts or slides off it. */
@media (hover: none) {
${body}
}
`)
console.log(`wrote ${OUT}`)
