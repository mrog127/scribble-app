// Mirrors every top-level `@media (hover: hover)` rule onto `:active`, so a
// touch device shows the same highlight while a finger is held down.
//
// Run after changing a hover rule:  node scripts/gen-touch-press.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCES = ['src/styles/layout.css', 'src/styles/cards.css']
const OUT = 'src/styles/touch-press.css'

// The ranges covered by desktop-only media queries — hover rules inside those
// describe the desktop layout and must not leak onto phones.
function desktopRanges(css) {
  const out = []
  const re = /@media[^{]*min-width[^{]*\{/g
  let m
  while ((m = re.exec(css))) {
    let i = m.index + m[0].length
    let depth = 1
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++
      else if (css[i] === '}') depth--
      i++
    }
    out.push([m.index, i])
    re.lastIndex = i
  }
  return out
}

// Pull out @media (hover: hover) blocks (balanced braces), skipping any that sit
// inside a desktop-only media query.
function hoverBlocks(css) {
  const out = []
  const skip = desktopRanges(css)
  const re = /@media\s*\(hover:\s*hover\)\s*\{/g
  let m
  while ((m = re.exec(css))) {
    if (skip.some(([a, b]) => m.index > a && m.index < b)) continue
    let i = m.index + m[0].length
    let depth = 1
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++
      else if (css[i] === '}') depth--
      i++
    }
    out.push(css.slice(m.index + m[0].length, i - 1))
    re.lastIndex = i
  }
  return out
}

const body = SOURCES.flatMap(f => hoverBlocks(readFileSync(f, 'utf8')))
  .join('\n')
  // Only rules that actually depend on hover are worth mirroring
  .split('\n')
  .join('\n')
  .replace(/:hover/g, ':active')

writeFileSync(OUT, `/* GENERATED by scripts/gen-touch-press.mjs — do not edit by hand.
   Every desktop hover rule, mirrored onto :active for touch devices, so pressing
   an element shows the same highlight until the finger lifts. */
@media (hover: none) {
${body}
}
`)
console.log(`wrote ${OUT}`)
